#include <iostream>
#include <vector>
#include <string>
#include <bitset>

class Solution {
public:
    int findIntegers(int n) {
        // Шаг 1: Генерируем числа Фибоначчи до 30-го бита (так как n <= 10^9 < 2^30)
        std::vector<int> f(31);
        f[0] = 1;
        f[1] = 2;
        for (int i = 2; i < 31; ++i) {
            f[i] = f[i - 1] + f[i - 2];
        }

        int result = 0;
        int prev_bit = 0;
        
        // Шаг 2: Идем от старшего бита (29) к младшему (0)
        for (int i = 29; i >= 0; --i) {
            // Проверяем, установлен ли i-й бит в числе n
            if ((n & (1 << i)) != 0) {
                // Если бит равен 1, прибавляем количество валидных комбинаций 
                // для оставшихся i позиций (если бы мы поставили на это место 0)
                result += f[i];
                
                // Если предыдущий бит тоже был 1, мы нашли две единицы подряд.
                // Дальше идти нельзя, прерываем цикл.
                if (prev_bit == 1) {
                    return result;
                }
                prev_bit = 1;
            } else {
                prev_bit = 0;
            }
        }

        // Если цикл завершился полностью, значит само число n тоже валидно
        return result + 1;
    }
};
